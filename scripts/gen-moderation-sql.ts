// Writes the generated moderation SQL from supabase/functions/_shared/moderationRules.ts, so the app, the profile-write
// function and the database use the same rules:
//   - the moderation section of supabase/schema.sql and of the moderation migration
//   - the parity block of supabase/tests/moderation.sql (the app's verdict for every string in scripts/moderation-corpus.ts)
// Run: npx tsx scripts/gen-moderation-sql.ts      (src/lib/__tests__/moderationSync.test.ts fails when these are stale)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CONTACT, DOMAINS, HOMOGLYPHS, NAME_REASONS, WORDS, checkText } from '../supabase/functions/_shared/moderationRules';
import { CORPUS } from './moderation-corpus';

export const MIGRATION = 'supabase/migrations/20261116174714_moderation_write_path.sql';
const START = '-- >>> moderation (generated by scripts/gen-moderation-sql.ts; do not edit by hand)';
const END = '-- <<< moderation';
const P_START = '-- >>> parity (generated by scripts/gen-moderation-sql.ts; do not edit by hand)';
const P_END = '-- <<< parity';

const noQuote = (s: string, what: string) => {
  if (s.includes("'")) throw new Error(`${what} must not contain single quotes`);
  return s;
};
// \y matches a word boundary at either end in Postgres regular expressions.
const words = (list: string[]) => noQuote(`\\y(?:${list.join('|')})\\y`, 'Patterns');
const raw = (list: string[]) => noQuote(list.map((p) => p.replace(/\\b/g, '\\y')).join('|'), 'Raw patterns');
const INVISIBLE = '[\\u0300-\\u036f\\u200b-\\u200f\\u2060-\\u2064\\ufeff\\u00ad\\u180e]';
const homoFrom = Object.keys(HOMOGLYPHS).join('');
const homoTo = Object.values(HOMOGLYPHS).join('');
if ([...homoFrom].length !== [...homoTo].length) throw new Error('Each homoglyph must map to one letter');
const LISTS = 'new.interests || new.skills || new.languages || new.goals || new.challenges || new.want_traits || new.foods || new.diet || new.availability';
const TEXT_COLS = ['first_name', 'last_name', 'org', 'intro', 'offer', 'area_name', 'status', 'field', 'from_field', 'mode', 'meet_mode', 'share_mode',
  'interests', 'skills', 'languages', 'goals', 'challenges', 'want_traits', 'foods', 'diet', 'availability'];

export function section(): string {
  return `${START}
-- Same rules as supabase/functions/_shared/moderationRules.ts, enforced in the database so a modified app cannot bypass them.
-- Blocks slurs, hate, sexual content, harassment, threats, scams, contact details and links, including leetspeak,
-- spaced-out and stretched letters, zero-width characters and lookalike letters. Rules only: the contextual AI check
-- runs in the profile-write edge function, never from SQL. Not evasion-proof.

create or replace function public.moderation_normalize(t text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
  s text;
  tok text;
  run text := '';
  res text[] := '{}';
  ch text;
begin
  s := normalize(lower(coalesce(t, '')), NFKD);
  s := regexp_replace(s, '${INVISIBLE}', '', 'g');
  s := translate(s, '${homoFrom}', '${homoTo}');
  -- "!", "|" and "+" stand in for letters only when a letter follows (k!ll), so "income!!!" stays "income".
  s := regexp_replace(s, '!(?=[a-z0-9@$])', 'i', 'g');
  s := regexp_replace(s, '[|](?=[a-z0-9@$])', 'i', 'g');
  s := regexp_replace(s, '[+](?=[a-z0-9@$])', 't', 'g');
  s := translate(s, '01345789@$', 'oieastbgas');
  s := btrim(regexp_replace(s, '[^a-z]+', ' ', 'g'));
  if s = '' then return ''; end if;
  foreach tok in array string_to_array(s, ' ') loop
    if length(tok) = 1 then
      run := run || tok;
    else
      if length(run) >= 3 then res := res || run;
      elsif run <> '' then
        foreach ch in array regexp_split_to_array(run, '') loop res := res || ch; end loop;
      end if;
      run := '';
      res := res || tok;
    end if;
  end loop;
  if length(run) >= 3 then res := res || run;
  elsif run <> '' then
    foreach ch in array regexp_split_to_array(run, '') loop res := res || ch; end loop;
  end if;
  return regexp_replace(array_to_string(res, ' '), '(.)\\1{2,}', '\\1', 'g');
end;
$$;

-- Raw text: accents, zero-width characters and lookalike letters folded; digits and symbols kept (phones, links, handles).
create or replace function public.moderation_raw(t text)
returns text
language sql
immutable
set search_path = ''
as $$
  select translate(
    lower(regexp_replace(normalize(coalesce(t, ''), NFKC), '${INVISIBLE}', '', 'g')),
    '${homoFrom}', '${homoTo}');
$$;

-- Free text (bios, messages, notes, chips): every list, contact details and links.
create or replace function public.moderation_is_clean(t text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select t is null or (
    public.moderation_normalize(t) !~ '${words(Object.values(WORDS).flat())}'
    and public.moderation_raw(t) !~ '${raw([...CONTACT, ...DOMAINS])}'
  );
$$;

-- Names of people and organisations: abuse lists and contact details only, so "Western Union", "Booking.com",
-- "Dick" or "Cummings" are fine, in any script.
create or replace function public.moderation_name_ok(t text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select t is null or (
    public.moderation_normalize(t) !~ '${words(NAME_REASONS.flatMap((r) => WORDS[r]))}'
    and public.moderation_raw(t) !~ '${raw(CONTACT)}'
  );
$$;

create or replace function public.profiles_moderation()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT'
     or (${TEXT_COLS.map((c) => `new.${c}`).join(', ')})
        is distinct from (${TEXT_COLS.map((c) => `old.${c}`).join(', ')}) then
    if not (public.moderation_name_ok(new.first_name) and public.moderation_name_ok(new.last_name) and public.moderation_name_ok(new.org)
            and public.moderation_is_clean(new.intro) and public.moderation_is_clean(new.offer) and public.moderation_is_clean(new.area_name)
            and public.moderation_is_clean(new.status) and public.moderation_is_clean(new.field) and public.moderation_is_clean(new.from_field)
            and public.moderation_is_clean(new.mode) and public.moderation_is_clean(new.meet_mode) and public.moderation_is_clean(new.share_mode)
            and not exists (select 1 from unnest(${LISTS}) s
                            where char_length(s) > 60 or not public.moderation_is_clean(s))) then
      raise exception 'content_blocked: profile text is not allowed';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_moderation on public.profiles;
create trigger profiles_moderation
  before insert or update on public.profiles
  for each row execute function public.profiles_moderation();

create or replace function public.requests_moderation()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if not public.moderation_is_clean(new.message) then
    raise exception 'content_blocked: message is not allowed';
  end if;
  return new;
end;
$$;

drop trigger if exists requests_moderation on public.connection_requests;
create trigger requests_moderation
  before insert on public.connection_requests
  for each row execute function public.requests_moderation();

create or replace function public.messages_moderation()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if not public.moderation_is_clean(new.body) then
    raise exception 'content_blocked: message is not allowed';
  end if;
  return new;
end;
$$;

drop trigger if exists messages_moderation on public.messages;
create trigger messages_moderation
  before insert on public.messages
  for each row execute function public.messages_moderation();
${END}
`;
}

export function parity(): string {
  const lines = CORPUS.map((t, i) => {
    if (t.includes('$c$')) throw new Error('Corpus strings must not contain $c$');
    return `  assert public.moderation_is_clean($c$${t}$c$) = ${checkText(t).ok}, 'parity text #${i}';\n` +
      `  assert public.moderation_name_ok($c$${t}$c$) = ${checkText(t, 'name').ok}, 'parity name #${i}';`;
  });
  return `${P_START}\n-- The app's verdicts (checkText) for scripts/moderation-corpus.ts; the database must agree.\ndo $parity$ begin\n${lines.join('\n')}\nend $parity$;\n${P_END}\n`;
}

/** Replaces the block between start and end markers (inclusive). Throws if the markers are missing. */
export function splice(text: string, start: string, end: string, block: string): string {
  const a = text.indexOf(start);
  const b = text.indexOf(end, a);
  if (a === -1 || b === -1) throw new Error(`markers not found: ${start}`);
  return text.slice(0, a) + block + text.slice(b + end.length + 1);
}

export const TARGETS: { file: string; start: string; end: string; build: () => string }[] = [
  { file: 'supabase/schema.sql', start: START, end: END, build: section },
  { file: MIGRATION, start: START, end: END, build: section },
  { file: 'supabase/tests/moderation.sql', start: P_START, end: P_END, build: parity },
];

if (require.main === module) {
  for (const t of TARGETS) {
    const path = join(__dirname, '..', t.file);
    writeFileSync(path, splice(readFileSync(path, 'utf8'), t.start, t.end, t.build()));
    console.log(`${t.file} updated`);
  }
}
